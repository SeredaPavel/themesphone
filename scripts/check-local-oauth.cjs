// Isolated PostgreSQL + Mailpit integration. Provider identities are fixtures; no real OAuth or SMTP.
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const dotenv=require('../backend/node_modules/dotenv');
const {createStrapi}=require('../backend/node_modules/@strapi/strapi');
const {createOAuthService}=require('../backend/src/lib/oauth-service');
const real=require('../backend/src/lib/oauth-providers');
let phase='setup';
async function main() {
  const env=dotenv.parse(fs.readFileSync(path.join(root,'.local/auth/backend.env')));
  const runtime=JSON.parse(fs.readFileSync(path.join(root,'.local/auth/runtime.json')));
  if(env.DATABASE_NAME!=='themesphone_auth_dev' || env.DATABASE_HOST!=='127.0.0.1' || env.DATABASE_PORT!=='5434' || env.SMTP_HOST!=='127.0.0.1' || env.SMTP_PORT!=='1026' || runtime.mailTransport!=='mailpit') throw Error('Refusing non-isolated database or real SMTP');
  const origin='http://127.0.0.1:3100';
  const bridge=dotenv.parse(fs.readFileSync(path.join(root,'.local/oauth/frontend.env')));
  Object.assign(process.env,env,{ENV_PATH:path.join(root,'.local/auth/backend.env'),AUTH_CONFIGURE_EMAIL:'false',DOCUMENTATION_ENABLED:'false',OAUTH_ENABLED:'true',OAUTH_ALLOWED_ORIGINS:origin,OAUTH_BRIDGE_SECRET:bridge.OAUTH_BRIDGE_SECRET,FRONTEND_URL:origin,STRAPI_API_URL:'http://127.0.0.1:1339'});
  delete process.env.DATABASE_URL;delete process.env.SMTP_USER;delete process.env.SMTP_PASS;
  process.chdir(path.join(root,'backend'));
  const strapi=createStrapi({appDir:process.cwd(),distDir:process.cwd()});
  await strapi.load();
  const q=uid=>strapi.db.query(uid),U='plugin::users-permissions.user',F='api::oauth-flow.oauth-flow',I='api::oauth-identity.oauth-identity';
  const jwt=strapi.plugin('users-permissions').service('jwt');
  const tag=Date.now();
  let subject='first-'+tag,claimedEmail='';
  const api={...real,configured:provider=>real.PROVIDERS.includes(provider),authorization:async(_provider,flow)=>'https://accounts.google.com/auth?state='+flow.state,exchange:async()=>({subject,email:claimedEmail})};
  const service=createOAuthService(strapi,api);
  const {confirmEmail,forgotPassword,resetPassword,login,register,me}=await import('../frontend/src/lib/email-auth.ts');
  const {oauthAction}=await import('../frontend/src/lib/oauth.ts');
  const request=(route,data,token)=>new Request(origin+'/api/'+route,{method:'POST',headers:{Origin:origin,...(token?{Cookie:'token='+token}:{})},body:JSON.stringify(data)});
  const userFor=async session=>q(U).findOne({where:{id:(await jwt.verify(session.jwt)).id}});
  async function start(provider='google',extra={}) {const result=await service.start({provider,origin,...extra});return {provider,origin,browser:result.browser,state:new URL(result.url).searchParams.get('state'),code:'fixture-code',...extra};}
  async function account(session,action,email) {return oauthAction(request('account/connections',{action,email},session.jwt),'account');}
  async function mailCode(email) {
    const box=await fetch('http://127.0.0.1:8026/api/v1/messages').then(response=>response.json());
    const message=box.messages.find(message=>message.To.some(to=>to.Address===email));
    assert.ok(message,'Expected local captured mail');
    const detail=await fetch('http://127.0.0.1:8026/api/v1/message/'+message.ID).then(response=>response.json());
    const match=(detail.Text || detail.HTML || '').match(/confirmation=([a-f0-9]{40})/);
    assert.ok(match,'Confirmation mail contains the link');
    return match[1];
  }
  const confirm=code=>confirmEmail(request('auth/email-confirmation',{confirmation:code}));
  const reset=(code,password)=>resetPassword(request('auth/reset-password',{code,password,passwordConfirmation:password}));
  try {
    phase='immediate OAuth login';
    const first=await start('telegram');
    await assert.rejects(service.finish({...first,browser:'b'.repeat(43)}),error=>error.code==='invalid_flow');
    const callbacks=await Promise.allSettled([service.finish(first),service.finish(first)]);
    assert.equal(callbacks.filter(result=>result.status==='fulfilled').length,1);
    const session=callbacks.find(result=>result.status==='fulfilled').value;
    assert.ok(session.jwt);assert.equal(session.pending,undefined);
    let user=await userFor(session);
    assert.equal(user.email,null);assert.equal(user.confirmed,true);assert.ok(!user.password);
    const response=await me(new Request(origin+'/api/me',{headers:{Cookie:'token='+session.jwt}}));
    assert.equal(response.status,200);assert.equal((await response.json()).email,null);
    for(const email of ['first,second@example.test','Name<second@example.test>']) assert.equal((await account(session,'add-email',email)).status,400);
    await assert.rejects(service.unlink({token:session.jwt,provider:'telegram'}),error=>error.code==='last_login_method');
    phase='concurrent first sign-ins';
    subject='parallel-'+tag;
    claimedEmail='provider-'+tag+'@example.test';
    const flows=[await start(),await start()];
    const parallel=await Promise.all(flows.map(flow=>service.finish(flow)));
    assert.equal((await jwt.verify(parallel[0].jwt)).id,(await jwt.verify(parallel[1].jwt)).id);
    assert.equal(await q(I).count({where:{key:real.digest('google:'+subject)}}),1);
    assert.equal((await userFor(parallel[0])).email,null,'Provider email is not silently assigned');
    const initialMail=await fetch('http://127.0.0.1:8026/api/v1/messages').then(response=>response.json());
    assert.equal(initialMail.messages.filter(message=>message.To.some(to=>to.Address===claimedEmail)).length,0,'OAuth first login sends no mandatory confirmation');
    claimedEmail='';
    phase='explicit linking and last-method protection';
    subject='linked-'+tag;
    assert.equal((await service.finish(await start('google',{mode:'link',token:session.jwt}))).linked,true);
    const unlinks=await Promise.allSettled([service.unlink({token:session.jwt,provider:'google'}),service.unlink({token:session.jwt,provider:'telegram'})]);
    assert.equal(unlinks.filter(result=>result.status==='fulfilled').length,1);
    const remaining=await q(I).findOne({where:{user:user.id}});
    const role=await q('plugin::users-permissions.role').findOne({where:{type:'authenticated'}});
    const other=await strapi.plugin('users-permissions').service('user').add({username:'other-'+tag,email:'other-'+tag+'@example.test',provider:'local',confirmed:true,blocked:false,role:role.id});
    const otherToken=jwt.issue({id:other.id});subject=remaining.subject;
    await assert.rejects(service.finish(await start(remaining.provider,{mode:'link',token:otherToken})),error=>error.code==='identity_in_use');
    phase='first password with pending email';
    const email='oauth-first-'+tag+'@example.test';
    assert.equal((await account(session,'create-password',email)).status,200);
    user=await q(U).findOne({where:{id:user.id}});
    assert.equal(user.email,null);assert.ok(!user.password);
    const setup=await q(F).findOne({where:{key:real.digest(user.resetPasswordToken)}});
    await q(F).update({where:{id:setup.id},data:{expiresAt:new Date(Date.now()-1000)}});
    assert.equal((await reset(user.resetPasswordToken,real.random())).status,400);
    assert.ok(!(await q(U).findOne({where:{id:user.id}})).password);
    await q(F).update({where:{id:setup.id},data:{expiresAt:new Date(Date.now()+60000)}});
    const password=real.random();
    const resets=await Promise.all([reset(user.resetPasswordToken,password),reset(user.resetPasswordToken,password)]);
    assert.equal(resets.filter(response=>response.status===200).length,1);
    user=await q(U).findOne({where:{id:user.id}});
    assert.equal(user.email,email);assert.ok(user.password);
    assert.equal((await login(request('login',{identifier:email,password}))).status,200);
    assert.equal((await service.connections({token:session.jwt})).hasPassword,true);
    await service.unlink({token:session.jwt,provider:remaining.provider});
    assert.equal(await q(I).count({where:{user:user.id}}),0);
    phase='email only and a password for the same account';
    subject='email-only-'+tag;
    const emailSession=await service.finish(await start('yandex'));
    const emailUser=await userFor(emailSession),emailOnly='oauth-mail-'+tag+'@example.test';
    assert.equal((await account(emailSession,'add-email',emailOnly)).status,200);
    assert.equal((await q(U).findOne({where:{id:emailUser.id}})).email,null);
    const confirmation=await mailCode(emailOnly);
    assert.equal((await confirm(confirmation)).status,200);
    assert.equal((await confirm(confirmation)).status,400);
    let emailRow=await q(U).findOne({where:{id:emailUser.id}});
    assert.equal(emailRow.email,emailOnly);assert.ok(!emailRow.password);
    assert.equal((await account(emailSession,'create-password','different-'+tag+'@example.test')).status,200);
    emailRow=await q(U).findOne({where:{id:emailUser.id}});
    const emailPassword=real.random();
    assert.equal((await reset(emailRow.resetPasswordToken,emailPassword)).status,200);
    assert.equal((await login(request('login',{identifier:emailOnly,password:emailPassword}))).status,200);
    assert.equal((await q(U).findOne({where:{id:emailUser.id}})).email,emailOnly);
    phase='existing email never merges accounts';
    claimedEmail=email;subject='same-email-'+tag;
    await assert.rejects(service.finish(await start('google')),error=>error.code==='account_exists');
    assert.equal(await q(I).count({where:{key:real.digest('google:'+subject)}}),0);
    claimedEmail='';subject='race-'+tag;
    const racing=await service.finish(await start('telegram')),racingUser=await userFor(racing);
    const raceEmail='oauth-race-'+tag+'@example.test',racePassword=real.random();
    assert.equal((await account(racing,'add-email',raceEmail)).status,200);
    const raceCode=await mailCode(raceEmail);
    const race=await Promise.all([confirm(raceCode),register(request('register',{email:raceEmail,password:racePassword}))]);
    assert.equal(race.filter(response=>response.status===200).length,1);
    assert.equal(await q(U).count({where:{email:raceEmail}}),1);
    const raceRow=await q(U).findOne({where:{id:racingUser.id}});
    assert.ok(raceRow.email===null || raceRow.email===raceEmail);
    phase='normal email registration and recovery';
    const normalEmail='oauth-normal-'+tag+'@example.test',normalPassword=real.random();
    assert.equal((await register(request('register',{email:normalEmail,password:normalPassword}))).status,200);
    let normal=await q(U).findOne({where:{email:normalEmail}});
    assert.equal(normal.confirmed,false);
    assert.equal((await confirm(normal.confirmationToken)).status,200);
    assert.equal((await login(request('login',{identifier:normalEmail,password:normalPassword}))).status,200);
    assert.equal((await forgotPassword(request('auth/forgot-password',{email:normalEmail}))).status,200);
    normal=await q(U).findOne({where:{id:normal.id}});
    const normalNew=real.random();
    assert.equal((await reset(normal.resetPasswordToken,normalNew)).status,200);
    assert.equal((await login(request('login',{identifier:normalEmail,password:normalNew}))).status,200);
    const missingEmail=await fetch('http://127.0.0.1:1339/api/auth/local/register',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({username:'missing-'+tag,password:real.random()})});
    assert.equal(missingEmail.status,400);
    phase='expired and blocked identities';
    const invalidSession=await start('google',{mode:'link',token:session.jwt});
    await assert.rejects(service.finish({...invalidSession,token:'invalid-token'}),error=>error.code==='login_required');
    const expired=await start();
    await q(F).update({where:{key:real.digest(expired.state)},data:{expiresAt:new Date(Date.now()-1000)}});
    await assert.rejects(service.finish(expired),error=>error.code==='invalid_flow');
    await q(U).update({where:{id:emailUser.id},data:{blocked:true}});
    await assert.rejects(service.connections({token:emailSession.jwt}),error=>error.code==='login_required');
    console.log('PASS: immediate OAuth sign-in without email; account without email loads; callback and first-login races; explicit linking and last method; single-use first-password link assigns email only after proof; independent email confirmation; collisions never merge; normal email registration and recovery; expired and blocked identities. Mailpit only.');
  } finally {await strapi.destroy();}
}
main().catch(error=>{fs.writeFileSync(path.join(root,'.local/oauth/integration-error.txt'),String(error.stack || error));console.error('OAuth integration check failed at '+phase+'; raw details remain in ignored .local/oauth/integration-error.txt.');process.exitCode=1;});
